def main():
    with ZipFile(SOURCE) as source:
        original = source.read('word/document.xml')
        tree = etree.fromstring(original)
        paragraphs = tree.find('w:body', NS).findall('w:p', NS)
        for index, replacement in REPLACEMENTS.items():
            nodes = paragraphs[index].findall('.//w:t', NS)
            assert nodes, index
            lengths = [len(n.text or '') for n in nodes]
            # Keep paragraph properties, runs, emphasis and drawings intact.
            # Text is allocated to the existing runs in original proportions.
            total = sum(lengths)
            cursor = cumulative = 0
            for j, (node, length) in enumerate(zip(nodes, lengths)):
                cumulative += length
                end = len(replacement) if j == len(nodes)-1 else round(len(replacement)*cumulative/max(1,total))
                node.text = replacement[cursor:end]
                node.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
                cursor = end
        xml = etree.tostring(tree, encoding='UTF-8', xml_declaration=True, standalone=True)
        # Correct misleading labels inside the existing figures, keeping their
        # pixel dimensions, geometry, colours and document anchors unchanged.
        font_path = '/tmp/opencode/font/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc'
        revised_media = {}
        def label(image, rect, lines, size=23):
            draw = ImageDraw.Draw(image)
            colour = image.getpixel((rect[0], rect[1]))
            draw.rectangle(rect, fill=colour)
            font = ImageFont.truetype(font_path, size)
            y = (rect[1]+rect[3]-len(lines)*(size+7))//2
            for line in lines:
                bbox = draw.textbbox((0,0),line,font=font)
                draw.text(((rect[0]+rect[2]-(bbox[2]-bbox[0]))//2,y),line,font=font,fill='#111111')
                y += size+7
        for name in ['word/media/image1.png', 'word/media/image2.png']:
            image = Image.open(BytesIO(source.read(name))).convert('RGB')
            if name.endswith('image1.png'):
                label(image, (740,1110,1010,1180), ['共享语言模型头', '冻结模式固定 / B相更新'])
            else:
                label(image, (930,530,1380,590), ['键值头：键与值使用', '同一组块号与权重'])
                label(image, (40,1035,1230,1090), ['（b）逐深度停机代价与批级在线局部停机'], 28)
                label(image, (700,1160,1210,1260), ['从最小深度起比较代价', '严格下降：保存代价与对应状态', '无需显式计算 softmax'])
                label(image, (1310,1160,1800,1270), ['首次不再下降（含相等）即停止', '用已保存深度的读出输出', '持续下降则运行全部循环'])
            buffer = BytesIO()
            image.save(buffer, format='PNG')
            revised_media[name] = buffer.getvalue()
        with ZipFile(TARGET, 'w') as target:
            for entry in source.infolist():
                target.writestr(entry, xml if entry.filename == 'word/document.xml' else revised_media.get(entry.filename, source.read(entry.filename)))
    with ZipFile(SOURCE) as a, ZipFile(TARGET) as b:
        assert a.namelist() == b.namelist()
        for name in a.namelist():
            if name in revised_media:
                assert Image.open(BytesIO(a.read(name))).size == Image.open(BytesIO(b.read(name))).size
            elif name != 'word/document.xml':
                assert a.read(name) == b.read(name), name
        old = etree.fromstring(a.read('word/document.xml'))
        new = etree.fromstring(b.read('word/document.xml'))
        for root in (old, new):
            for node in root.findall('.//w:t', NS):
                node.text = ''
                node.attrib.pop('{http://www.w3.org/XML/1998/namespace}space', None)
        assert etree.tostring(old) == etree.tostring(new), 'non-text layout changed'
    print(TARGET)
    print(f'Updated {len(REPLACEMENTS)} paragraphs and figure labels; layout properties and image dimensions preserved.')

if __name__ == '__main__':
    main()
